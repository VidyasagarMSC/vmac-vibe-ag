export const allArticles: Article[] = baseArticles.map((article, index) => ({
  ...article,
  id: `article-${index + 1}`,
  slug: slugify(article.title),
}))

export function getArticleBySlug(slug: string): Article | undefined {
  return allArticles.find((a) => a.slug === slug)
}

export function getArticlesByPlatform(platform: Article["platform"]): Article[] {
  return allArticles.filter((a) => a.platform === platform)
}

export function getArticlesByCategory(category: Article["category"]): Article[] {
  return allArticles.filter((a) => a.category === category)
}

export function getAllTopics(): string[] {
  const topics = new Set<string>()
  allArticles.forEach((a) => a.topics.forEach((t) => topics.add(t)))
  return Array.from(topics).sort()
}

export function getRelatedArticles(article: Article, limit = 3): Article[] {
  return allArticles
    .filter((a) => a.id !== article.id)
    .map((a) => ({
      article: a,
      score: a.topics.filter((t) => article.topics.includes(t)).length,
    }))
    .filter((a) => a.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((a) => a.article)
}

